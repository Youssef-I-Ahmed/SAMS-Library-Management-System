import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config.settings import get_settings
from src.rag.llm import get_provider
from src.service import build_services
from src.rag.answer import AnswerService


def main():
    settings = get_settings()
    provider = get_provider(settings)

    print("Provider:", provider.name if provider else None)

    if provider is None:
        print("No LLM provider configured.")
        raise SystemExit(2)

    services = build_services(settings)
    answer_service = AnswerService(
        services.engine,
        provider,
        settings,
    )

    questions = [
        "ما هي المشروعات المتعلقة بالتسويق الإلكتروني؟",
        "Which projects deal with banking service quality?",
    ]

    for question in questions:
        result = answer_service.ask(question)

        language = (
            "Arabic"
            if any("\u0600" <= char <= "\u06ff" for char in question)
            else "English"
        )

        print("\nLanguage:", language)
        print("Status:", result.status)
        print("Generated by:", result.generated_by)
        print(
            "Verification problems:",
            result.evidence.verification_problems,
        )
        print("Citations valid:", result.citations_valid)
        print(
            "LLM error:",
            result.llm.error_kind if result.llm else None,
        )
        print("Retrieved source count:", len(result.sources))
        print("Answer present:", bool(result.answer))


if __name__ == "__main__":
    main()