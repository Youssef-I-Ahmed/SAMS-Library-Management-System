#!/usr/bin/env python
"""Compare two versions of Project.xlsx (raw cell level, keyed by BOOK_CODE, never by name similarity).

    python scripts/compare_datasets.py OLD.xlsx NEW.xlsx [--out docs/DATASET_COMPARISON.md]
"""
from __future__ import annotations

import argparse
import collections
import re
import sys
from pathlib import Path

import openpyxl

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data.loader import sha256_file  # noqa: E402
from src.data.schema import SOURCE_COLUMNS, canonical_header  # noqa: E402


def load(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb[wb.sheetnames[0]]
    it = ws.iter_rows(values_only=True)
    raw_header = list(next(it))
    header = [canonical_header(h) for h in raw_header]
    rows, order, dup = {}, [], collections.Counter()
    for n, r in enumerate(it, start=2):
        if r is None or all(c is None or str(c).strip() == "" for c in r):
            continue
        d = {h: ("" if c is None else str(c)) for h, c in zip(header, r)}
        k = d.get("BOOK_CODE", "").strip()
        dup[k] += 1
        if k in rows:
            continue
        d["_row"] = n
        rows[k] = d
        order.append(k)
    return {"sheet": ws.title, "raw_header": raw_header, "header": header, "rows": rows, "order": order,
            "dups": {k: v for k, v in dup.items() if v > 1}}


def ws(s):
    return re.sub(r"\s+", " ", s).strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("old"); ap.add_argument("new")
    ap.add_argument("--out", default="docs/DATASET_COMPARISON.md")
    a = ap.parse_args()
    o, n = load(a.old), load(a.new)
    L = ["# Dataset comparison (old vs new Project.xlsx)", "",
         "Generated by `scripts/compare_datasets.py`; keyed by `BOOK_CODE` (never by name similarity). "
         "Values are compared as raw cell text; the third column of each table shows whitespace-only differences separately.", ""]
    L += ["## Files", "", "| | old (historical) | new (authoritative) |", "|---|---|---|",
          f"| sha256 | `{sha256_file(Path(a.old))}` | `{sha256_file(Path(a.new))}` |",
          f"| size (bytes) | {Path(a.old).stat().st_size} | {Path(a.new).stat().st_size} |",
          f"| sheet | {o['sheet']} | {n['sheet']} |",
          f"| data rows | {len(o['order'])} | {len(n['order'])} |",
          f"| duplicate BOOK_CODE | {len(o['dups'])} | {len(n['dups'])} |", ""]
    L += ["## Column names", "", "| position | old | new | canonical |", "|---|---|---|---|"]
    for i in range(max(len(o["raw_header"]), len(n["raw_header"]))):
        ro = o["raw_header"][i] if i < len(o["raw_header"]) else None
        rn = n["raw_header"][i] if i < len(n["raw_header"]) else None
        e = lambda x: repr(x).replace("|", "\\|")
        L.append(f"| {i+1} | `{e(ro)}` | `{e(rn)}` | `{canonical_header(rn).replace('|', chr(92)+'|')}` |" + (" **renamed**" if ro != rn else " |"))
    L.append("")
    missing = [c for c in SOURCE_COLUMNS if c not in n["header"]]
    L += [f"Columns the application requires that are absent from the new file after header canonicalisation: {missing or 'none'}.", ""]
    ok, nk = set(o["rows"]), set(n["rows"])
    added, removed, common = sorted(nk - ok), sorted(ok - nk), sorted(ok & nk)
    L += ["## Records", "", f"* common BOOK_CODE: {len(common)}", f"* added in new: {len(added)}", f"* removed from new: {len(removed)}"]
    if o["order"] == n["order"]:
        L.append("* row order identical")
    for lab, ks, src in (("Added", added, n), ("Removed", removed, o)):
        if ks:
            L += ["", f"### {lab} (first 15)", ""] + [f"* `{k}` — {src['rows'][k]['TITLE'][:90]}" for k in ks[:15]]
    cols = [c for c in SOURCE_COLUMNS if c != "BOOK_CODE"]
    chg = {c: [] for c in cols}; wsonly = collections.Counter(); changed_rows = set()
    for k in common:
        for c in cols:
            x, y = o["rows"][k].get(c, ""), n["rows"][k].get(c, "")
            if x != y:
                if ws(x) == ws(y):
                    wsonly[c] += 1
                else:
                    chg[c].append((k, x, y)); changed_rows.add(k)
    L += ["", "## Field-level changes in common records", "", "| field | changed (substantive) | whitespace-only |", "|---|---|---|"]
    for c in cols:
        L.append(f"| {c.replace(chr(124), chr(92)+chr(124))} | {len(chg[c])} | {wsonly[c]} |")
    L += ["", f"Records with at least one substantive change: **{len(changed_rows)}** of {len(common)}.", ""]
    for c in cols:
        if chg[c]:
            L += [f"### {c.replace(chr(124), chr(92)+chr(124))}: examples (up to 12)", "", "| BOOK_CODE | old | new |", "|---|---|---|"]
            for k, x, y in chg[c][:12]:
                L.append(f"| {k} | {x[:80]!r} | {y[:80]!r} |")
            L.append("")
    L += ["## Missing-value (NA) counts per column", "", "| column | old NA | new NA |", "|---|---|---|"]
    for c in cols:
        f = lambda d: sum(1 for r in d["rows"].values() if r.get(c, "").strip().upper() in ("", "NA"))
        L.append(f"| {c.replace(chr(124), chr(92)+chr(124))} | {f(o)} | {f(n)} |")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:60]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
